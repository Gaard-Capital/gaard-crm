/* ======================================================================
   007  EMAIL TEMPLATES, SHARED BY THE TEAM
   Run once in the Supabase SQL Editor. Safe to run again.

   The letters the mail merge fills (Follow-ups > Email templates) were kept
   in each person's browser. They now live here, so everyone writes from the
   same wording and a change one person makes is there for the rest.

   1. The email_templates table, under row level security like every other
      table (team members read and write), with the audit trigger.
   2. apply_changes() is allowed to write it.

   The table starts empty. The first time someone signs in afterwards, the
   app fills it with the starting templates it ships with.
   ====================================================================== */

begin;

create table if not exists public.email_templates (
  id           bigint generated by default as identity primary key,
  name         text not null,
  segment_code text references public.segments(code),
  subject      text not null default '',
  body         text not null default '',
  is_first     boolean not null default false,   -- the first cold outreach letter
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

alter table public.email_templates enable row level security;
drop policy if exists team_read   on public.email_templates;
drop policy if exists team_insert on public.email_templates;
drop policy if exists team_update on public.email_templates;
drop policy if exists team_delete on public.email_templates;
create policy team_read   on public.email_templates for select to authenticated using (public.is_team_member());
create policy team_insert on public.email_templates for insert to authenticated with check (public.is_team_member());
create policy team_update on public.email_templates for update to authenticated using (public.is_team_member()) with check (public.is_team_member());
create policy team_delete on public.email_templates for delete to authenticated using (public.is_team_member());
grant select, insert, update, delete on public.email_templates to authenticated;
revoke all on public.email_templates from anon;

drop trigger if exists zz_audit on public.email_templates;
create trigger zz_audit after insert or update or delete on public.email_templates
  for each row execute function public.audit_row();

create or replace function public.apply_changes(p_changes jsonb)
 returns jsonb
 language plpgsql
 security invoker
 set search_path to 'public', 'pg_temp'
as $$
declare
  ch      jsonb;
  t       text;
  op      text;
  r       jsonb;
  cols    text;
  sets    text;
  n       int := 0;
  inserted text[] := '{}';
  allowed constant text[] := array['team_members', 'events', 'campaigns', 'organizations', 'contacts', 'rfps',
                                   'touchpoints', 'opportunities', 'reminders', 'email_messages', 'flag_rules',
                                   'email_templates'];
begin
  if auth.uid() is null or not public.is_team_member() then
    raise exception 'Sign in as a team member, with your two-step code, to save changes' using errcode = '42501';
  end if;

  perform set_config('app.seeding', 'on', true);

  for ch in select value from jsonb_array_elements(p_changes) loop
    t  := ch->>'table';
    op := ch->>'op';
    r  := coalesce(ch->'row', '{}'::jsonb);
    if not (t = any (allowed)) then
      raise exception 'The app cannot change the table %', t;
    end if;

    if op = 'delete' then
      execute format('delete from public.%I where id = $1', t) using (ch->>'id')::bigint;
    else
      select string_agg(quote_ident(c.column_name), ', ' order by c.ordinal_position),
             string_agg(format('%I = r.%I', c.column_name, c.column_name), ', ' order by c.ordinal_position)
               filter (where c.column_name <> 'id')
        into cols, sets
        from information_schema.columns c
       where c.table_schema = 'public' and c.table_name = t
         and c.is_generated = 'NEVER' and r ? c.column_name;
      if cols is null then continue; end if;

      if op = 'insert' then
        execute format('insert into public.%I (%s) select %s from jsonb_populate_record(null::public.%I, $1)', t, cols, cols, t)
          using r;
        if not (t = any (inserted)) then inserted := inserted || t; end if;
      elsif op = 'update' then
        if sets is null then continue; end if;
        execute format('update public.%I set %s from jsonb_populate_record(null::public.%I, $1) r where %I.id = $2', t, sets, t, t)
          using r, (ch->>'id')::bigint;
      else
        raise exception 'Unknown change "%"', op;
      end if;
    end if;
    n := n + 1;
  end loop;

  foreach t in array inserted loop
    begin
      execute format('select setval(pg_get_serial_sequence(%L, %L), greatest((select max(id) from public.%I), 1))',
                     'public.' || t, 'id', t);
    exception when insufficient_privilege then null;   -- the counter catches up on the next database insert instead
    end;
  end loop;

  return jsonb_build_object('applied', n);
end $$;

revoke execute on function public.apply_changes(jsonb) from public, anon;
grant  execute on function public.apply_changes(jsonb) to authenticated;

commit;
