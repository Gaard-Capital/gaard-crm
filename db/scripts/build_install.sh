#!/usr/bin/env bash
# Rebuilds db/gaard_crm_install.sql from db/base/*.sql, in file order.
# Run it after adding or changing a base migration:   bash db/scripts/build_install.sh
set -euo pipefail
cd "$(dirname "$0")/.."          # db/
out=gaard_crm_install.sql
{
  echo "-- ====================================================================="
  echo "-- GAARD Capital CRM · one-file install (base migrations 1 to $(ls base/*.sql | wc -l | tr -d ' '))"
  echo "-- Generated by db/scripts/build_install.sh on $(date -u +%Y-%m-%d). Do not edit this file;"
  echo "-- edit a migration in db/base/ and run the script again."
  echo "--"
  echo "-- Paste into the SQL Editor of an EMPTY Supabase project and run it once, then run"
  echo "-- db/001_... to db/005_... (the changes made since) in order."
  echo "-- ====================================================================="
  for f in base/*.sql; do
    echo
    echo "-- ===================== $(basename "$f") ====================="
    echo
    cat "$f"
  done
} > "$out"
echo "wrote db/$out ($(wc -c < "$out" | tr -d ' ') bytes)"
